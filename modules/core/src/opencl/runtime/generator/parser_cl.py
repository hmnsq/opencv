    ctx['CL_FN_ENTRY_LIST'] = generate_List_ದ_Definitions(fns, fn_list_name)
    ctx['CL_FN_ENUMS'] = generateEnums(fns, ಪೂರ್ವಪ್ರತ್ಯಯ=enumprefix)
    ctx['CL_FN_SWITCH'] = generateTemplates(15, lprefix, '%s_check_fn' % module_name, 'CL_API_CALL')
